function getLocale() {
  try {
    const raw = localStorage.getItem("Comfy.Locale") || "";
    const code = String(raw).split(/[-_]/)[0].toLowerCase();
    return code === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}

function t(key, vars) {
  let s = (ZH && ZH[key]) || key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = String(s).split(`{${k}}`).join(String(vars[k]));
    }
  }
  return s;
}

